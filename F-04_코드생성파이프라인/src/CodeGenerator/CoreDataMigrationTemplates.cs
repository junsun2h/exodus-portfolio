        /// <summary>
        /// 파일 헤더 생성 (공통 타입 import 포함)
        /// </summary>
        public static string GenerateFileHeader(string coreDataName, HashSet<string> usedTypes = null)
        {
            var sb = new StringBuilder();

            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// This file was generated; DO NOT EDIT!");
            sb.AppendLine("// source: CodeGenerator_CoreDataMigration.cs");
            sb.AppendLine($"// CoreData: {coreDataName}");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();

            // MigrationFunction import
            sb.AppendLine("import { MigrationFunction } from \"../CoreDataMigration\";");

            // 공통 타입 import (Generated 폴더에서 3단계 위로)
            sb.AppendLine("import { ModValue, ModValueInt, ModValueDouble, ModValueBool } from \"../../../Data/Shared/Types/ModValueTypes\";");
            sb.AppendLine("import { PXBigInt } from \"../../../Data/Shared/Types/BigIntTypes\";");

            // 사용된 Enum들 import (CommonEnum에서)
            if (usedTypes != null && usedTypes.Count > 0)
            {
                var enumTypes = usedTypes.Where(t => t.StartsWith("E") && char.IsUpper(t[1])).ToList();
                if (enumTypes.Count > 0)
                {
                    string enumImports = string.Join(", ", enumTypes.OrderBy(e => e));
                    sb.AppendLine($"import {{ {enumImports} }} from \"../../../Data/Generated/CommonEnum\";");
                }

                // CoreData 타입들 import (CoreData_ 접두사 또는 Info 접미사)
                var coreDataTypes = usedTypes.Where(t =>
                    t.StartsWith("CoreData_") ||
                    t.EndsWith("Info") ||
                    t.EndsWith("Data")).ToList();
                if (coreDataTypes.Count > 0)
                {
                    string coreDataImports = string.Join(", ", coreDataTypes.OrderBy(c => c));
                    sb.AppendLine($"import {{ {coreDataImports} }} from \"../../../Data/Generated/CoreData\";");
                }
            }

            sb.AppendLine();

            return sb.ToString();
        }

        /// <summary>
        /// 스키마에서 사용된 타입들 수집
        /// </summary>
        public static HashSet<string> CollectUsedTypes(List<SchemaVersion> versions)
        {
            var usedTypes = new HashSet<string>();

            foreach (var version in versions)
            {
                if (version.Schema?.Fields == null) continue;

                foreach (var field in version.Schema.Fields.Values)
                {
                    ExtractTypesFromTypeString(field.TypeScriptType, usedTypes);
                }
            }

            return usedTypes;
        }

        /// <summary>
        /// 타입 문자열에서 실제 타입들 추출
        /// </summary>
        private static void ExtractTypesFromTypeString(string typeStr, HashSet<string> usedTypes)
        {
            if (string.IsNullOrEmpty(typeStr)) return;

            // Map<K, V> 또는 Array<T> 형태 처리
            if (typeStr.StartsWith("Map<") || typeStr.StartsWith("Array<"))
            {
                // 제네릭 파라미터 추출
                int start = typeStr.IndexOf('<') + 1;
                int end = typeStr.LastIndexOf('>');
                if (start > 0 && end > start)
                {
                    string inner = typeStr.Substring(start, end - start);
                    // 쉼표로 분리 (Map의 경우)
                    foreach (string part in inner.Split(','))
                    {
                        ExtractTypesFromTypeString(part.Trim(), usedTypes);
                    }
                }
            }
            else
            {
                // 기본 타입 제외
                if (typeStr == "string" || typeStr == "number" || typeStr == "boolean" || typeStr == "any")
                    return;

                // ModValue 계열은 이미 공통 import에 포함
                if (typeStr.StartsWith("ModValue") || typeStr == "PXBigInt")
                    return;

                usedTypes.Add(typeStr);
            }
        }

        /// <summary>
        /// 인터페이스 정의 생성
        /// </summary>
        public static string GenerateInterface(string coreDataName, string version, CoreDataSchema schema, bool isLatest)
        {
            var sb = new StringBuilder();
            string versionSuffix = version.Replace(".", "_");
            string interfaceName = isLatest
                ? $"{coreDataName}_Data_Latest"
                : $"{coreDataName}_Data_v{versionSuffix}";

            sb.AppendLine($"interface {interfaceName} {{");

            foreach (var field in schema.Fields.Values)
            {
                sb.AppendLine($"{INDENT1}{field.Name}?: {field.TypeScriptType};");
            }

            sb.AppendLine($"{INDENT1}[str: string]: any;");
            sb.AppendLine("}");

            return sb.ToString();
        }

        /// <summary>
        /// 버전별 인터페이스 상속 체인 생성
        /// </summary>
        public static string GenerateInterfaceChain(string coreDataName, List<SchemaVersion> versions)
        {
            var sb = new StringBuilder();

            sb.AppendLine("// -----------------------------------------------");
            sb.AppendLine($"// {coreDataName} - Auto-generated interfaces");
            sb.AppendLine("// -----------------------------------------------");
            sb.AppendLine();

            for (int i = 0; i < versions.Count; i++)
            {
                var version = versions[i];
                bool isLatest = i == versions.Count - 1;
                string versionSuffix = version.Version.Replace(".", "_");

                if (i == 0)
                {
                    // 첫 버전: 기본 인터페이스
                    sb.AppendLine($"interface {coreDataName}_Data_v{versionSuffix} {{");
                    foreach (var field in version.Schema.Fields.Values)
                    {
                        sb.AppendLine($"{INDENT1}{field.Name}?: {field.TypeScriptType};");
                    }
                    sb.AppendLine($"{INDENT1}[str: string]: any;");
                    sb.AppendLine("}");
                }
                else
                {
                    // 이후 버전: 이전 버전 상속
                    string prevVersionSuffix = versions[i - 1].Version.Replace(".", "_");
                    sb.AppendLine();
                    sb.AppendLine($"interface {coreDataName}_Data_v{versionSuffix} extends {coreDataName}_Data_v{prevVersionSuffix} {{");

                    // 변경된 필드만 추가
                    if (version.Changes != null)
                    {
                        foreach (var change in version.Changes)
                        {
                            if (change.Type == SchemaChangeType.FieldAdded)
                            {
                                sb.AppendLine($"{INDENT1}{change.FieldName}?: {change.NewType};");
                            }
                            else if (change.Type == SchemaChangeType.FieldRenamed)
                            {
                                sb.AppendLine($"{INDENT1}{change.FieldName}?: {change.NewType};");
                            }
                        }
                    }
                    sb.AppendLine("}");
                }

                // Latest 인터페이스
                if (isLatest)
                {
                    sb.AppendLine();
                    sb.AppendLine($"interface {coreDataName}_Data_Latest extends {coreDataName}_Data_v{versionSuffix} {{}}");
                }
            }

            return sb.ToString();
        }

