        /// <summary>
        /// 마이그레이션 함수 객체 생성
        /// </summary>
        public static string GenerateMigrationObject(string coreDataName, List<SchemaVersion> versions)
        {
            var sb = new StringBuilder();

            sb.AppendLine();
            sb.AppendLine("// -----------------------------------------------");
            sb.AppendLine($"// {coreDataName} - Auto-generated migrations");
            sb.AppendLine("// -----------------------------------------------");
            sb.AppendLine($"export const {coreDataName}_Migrations_Generated: {{ [key: string]: MigrationFunction<any, any> }} = {{");

            for (int i = 1; i < versions.Count; i++)
            {
                var version = versions[i];
                var prevVersion = versions[i - 1];

                if (version.Changes == null || version.Changes.Count == 0)
                    continue;

                string prevVersionSuffix = prevVersion.Version.Replace(".", "_");
                string newVersionSuffix = version.Version.Replace(".", "_");
                string prevInterface = $"{coreDataName}_Data_v{prevVersionSuffix}";
                string newInterface = $"{coreDataName}_Data_v{newVersionSuffix}";

                // 같은 버전의 모든 변경사항을 하나의 함수로 병합
                string migrationCode = GenerateMergedMigration(version.Version, prevInterface, newInterface, version.Changes);
                if (!string.IsNullOrEmpty(migrationCode))
                {
                    sb.AppendLine(migrationCode);
                }
            }

            sb.AppendLine("};");

            return sb.ToString();
        }

        /// <summary>
        /// 같은 버전의 여러 변경사항을 하나의 마이그레이션 함수로 병합
        /// </summary>
        private static string GenerateMergedMigration(string version, string prevInterface, string newInterface, List<SchemaChange> changes)
        {
            if (changes == null || changes.Count == 0)
                return string.Empty;

            // 변경 타입별로 분류
            var addedFields = changes.Where(c => c.Type == SchemaChangeType.FieldAdded).ToList();
            var removedFields = changes.Where(c => c.Type == SchemaChangeType.FieldRemoved).ToList();
            var renamedFields = changes.Where(c => c.Type == SchemaChangeType.FieldRenamed).ToList();
            var typeChangedFields = changes.Where(c => c.Type == SchemaChangeType.FieldTypeChanged).ToList();
            var nestedAddedFields = changes.Where(c => c.Type == SchemaChangeType.NestedFieldAdded).ToList();
            var nestedRemovedFields = changes.Where(c => c.Type == SchemaChangeType.NestedFieldRemoved).ToList();
            var nestedRenamedFields = changes.Where(c => c.Type == SchemaChangeType.NestedFieldRenamed).ToList();
            var nestedTypeChangedFields = changes.Where(c => c.Type == SchemaChangeType.NestedFieldTypeChanged).ToList();

            var sb = new StringBuilder();
            sb.AppendLine($"{INDENT1}\"{version}\": (data: {prevInterface}): {newInterface} => {{");

            // 삭제할 필드 처리 (먼저 추출)
            if (removedFields.Count > 0)
            {
                string removedFieldNames = string.Join(", ", removedFields.Select(c => c.FieldName));
                sb.AppendLine($"{INDENT2}const {{ {removedFieldNames}, ...rest }} = data;");
            }

            // 이름 변경 필드 처리
            foreach (var change in renamedFields)
            {
                sb.AppendLine($"{INDENT2}const {change.FieldName} = data.{change.OldFieldName};");
            }

            // 타입 변경 필드 처리
            foreach (var change in typeChangedFields)
            {
                string convertCode = GenerateTypeConversionCode(change.FieldName, change.OldType, change.NewType);
                sb.AppendLine($"{INDENT2}{convertCode}");
            }

            // 중첩 필드 삭제를 위한 부모 필드 처리
            var nestedRemovedByParent = nestedRemovedFields.GroupBy(c => c.NestedFieldPath.Split('.')[0]).ToList();
            foreach (var group in nestedRemovedByParent)
            {
                string parentField = group.Key;
                var fieldNames = group.Select(c => c.NestedFieldPath.Split('.').Last()).ToList();
                string removedNames = string.Join(", ", fieldNames);
                sb.AppendLine($"{INDENT2}const {{ {removedNames}, ...rest_{parentField} }} = data.{parentField} || {{}};");
            }

            // 중첩 필드 이름 변경 처리
            var nestedRenamedByParent = nestedRenamedFields.GroupBy(c => c.NestedFieldPath.Split('.')[0]).ToList();
            foreach (var group in nestedRenamedByParent)
            {
                string parentField = group.Key;
                foreach (var change in group)
                {
                    string oldFieldName = change.OldFieldName ?? change.FieldName;
                    string newFieldName = change.FieldName;
                    sb.AppendLine($"{INDENT2}const renamed_{parentField}_{newFieldName} = data.{parentField}?.{oldFieldName};");
                }
            }

            // 중첩 필드 타입 변경 처리
            foreach (var change in nestedTypeChangedFields)
            {
                string parentField = change.NestedFieldPath.Split('.')[0];
                string fieldName = change.NestedFieldPath.Split('.').Last();
                string convertCode = GenerateTypeConversionCode($"data.{parentField}?.{fieldName}", change.OldType, change.NewType);
                sb.AppendLine($"{INDENT2}const converted_{parentField}_{fieldName} = {convertCode.Replace($"const converted_{parentField}_{fieldName} = ", "")};");
            }

            // return 문 생성
            sb.Append($"{INDENT2}return {{ ");

            // 기존 데이터 스프레드
            if (removedFields.Count > 0)
                sb.Append("...rest");
            else
                sb.Append("...data");

            // 추가 필드
            foreach (var change in addedFields)
            {
                sb.Append($", {change.FieldName}: {change.DefaultValue}");
            }

            // 이름 변경 필드 (새 이름으로)
            foreach (var change in renamedFields)
            {
                sb.Append($", {change.FieldName}: {change.FieldName}");
            }

            // 타입 변경 필드
            foreach (var change in typeChangedFields)
            {
                sb.Append($", {change.FieldName}: converted_{change.FieldName}");
            }

            // 중첩 필드 처리 (추가, 삭제, 이름변경, 타입변경 통합)
            var allNestedChanges = nestedAddedFields
                .Concat(nestedRemovedFields)
                .Concat(nestedRenamedFields)
                .Concat(nestedTypeChangedFields)
                .GroupBy(c => c.NestedFieldPath.Split('.')[0])
                .ToList();

            foreach (var group in allNestedChanges)
            {
                string parentField = group.Key;
                bool hasRemoved = nestedRemovedByParent.Any(g => g.Key == parentField);

                sb.Append($", {parentField}: {{ ");
                if (hasRemoved)
                    sb.Append($"...rest_{parentField}");
                else
                    sb.Append($"...data.{parentField}");

                // 추가된 중첩 필드
                foreach (var change in group.Where(c => c.Type == SchemaChangeType.NestedFieldAdded))
                {
                    string fieldName = change.NestedFieldPath.Split('.').Last();
                    sb.Append($", {fieldName}: {change.DefaultValue}");
                }

                // 이름 변경된 중첩 필드
                foreach (var change in group.Where(c => c.Type == SchemaChangeType.NestedFieldRenamed))
                {
                    string newFieldName = change.FieldName;
                    sb.Append($", {newFieldName}: renamed_{parentField}_{newFieldName}");
                }

                // 타입 변경된 중첩 필드
                foreach (var change in group.Where(c => c.Type == SchemaChangeType.NestedFieldTypeChanged))
                {
                    string fieldName = change.NestedFieldPath.Split('.').Last();
                    sb.Append($", {fieldName}: converted_{parentField}_{fieldName}");
                }

                sb.Append(" }");
            }

            sb.AppendLine(" };");
            sb.Append($"{INDENT1}}},");

            return sb.ToString();
        }

        /// <summary>
        /// 타입 변환 코드 생성
        /// </summary>
        private static string GenerateTypeConversionCode(string fieldName, string oldType, string newType)
        {
            string varName = fieldName.Replace(".", "_").Replace("?", "");
            if (varName.StartsWith("data_"))
                varName = varName.Substring(5);

            // 기본 타입 변환 규칙
            if (oldType == "number" && newType == "string")
            {
                return $"const converted_{varName} = String(data.{fieldName} ?? \"\");";
            }
            else if (oldType == "string" && newType == "number")
            {
                return $"const converted_{varName} = Number(data.{fieldName}) || 0;";
            }
            else if (oldType == "boolean" && newType == "string")
            {
                return $"const converted_{varName} = String(data.{fieldName} ?? false);";
            }
            else if (oldType == "string" && newType == "boolean")
            {
                return $"const converted_{varName} = data.{fieldName} === \"true\";";
            }
            else if (oldType == "number" && newType == "boolean")
            {
                return $"const converted_{varName} = Boolean(data.{fieldName});";
            }
            else if (oldType == "boolean" && newType == "number")
            {
                return $"const converted_{varName} = data.{fieldName} ? 1 : 0;";
            }
            else if (newType == "ModValueInt" && (oldType == "number" || oldType == "string"))
            {
                return $"const converted_{varName} = ModValueInt.create(Number(data.{fieldName}) || 0);";
            }
            else if (oldType == "ModValueInt" && newType == "number")
            {
                return $"const converted_{varName} = data.{fieldName}?.GetValue() ?? 0;";
            }
            else
            {
                // 알 수 없는 타입 변환은 TODO 표시
                return $"const converted_{varName} = data.{fieldName}; // TODO: {oldType} -> {newType} 변환 로직 필요";
            }
        }

        /// <summary>
        /// 전체 마이그레이션 파일 생성
        /// </summary>
        public static string GenerateFullMigrationFile(string coreDataName, SchemaHistory history)
        {
            var sb = new StringBuilder();

            // 사용된 타입 수집
            HashSet<string> usedTypes = CollectUsedTypes(history.Versions);

            // 헤더 (import 포함)
            sb.Append(GenerateFileHeader(coreDataName, usedTypes));

            // 인터페이스 체인
            sb.Append(GenerateInterfaceChain(coreDataName, history.Versions));
            sb.AppendLine();

            // 마이그레이션 함수
            sb.Append(GenerateMigrationObject(coreDataName, history.Versions));

            return sb.ToString();
        }

        /// <summary>
        /// CoreDataVersions.generated.ts 파일 생성
        /// </summary>
        public static string GenerateVersionsFile(Dictionary<string, string> coreDataVersions)
        {
